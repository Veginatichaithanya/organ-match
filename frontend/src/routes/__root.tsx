function ErrorComponent({ error, reset }: { error: Error; reset: () => void }) {
  console.error("Route error caught by root ErrorComponent:", error);
  const router = useRouter();

  const errorMessage = error?.message || String(error) || "An unexpected error occurred.";
  const isAuthError =
    errorMessage.toLowerCase().includes("unauthorized") ||
    errorMessage.toLowerCase().includes("401") ||
    errorMessage.toLowerCase().includes("token") ||
    errorMessage.toLowerCase().includes("forbidden") ||
    errorMessage.toLowerCase().includes("403");

  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-lg w-full text-center space-y-4 p-6 bg-card border border-border rounded-xl shadow-sm">
        <div className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-red-100 dark:bg-red-950 text-red-600">
          <svg className="h-6 w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-3L13.732 4c-.77-1.333-2.694-1.333-3.464 0L3.34 16c-.77 1.333.192 3 1.732 3z" />
          </svg>
        </div>

        <h1 className="text-xl font-semibold tracking-tight text-foreground">
          {isAuthError ? "Session Expired or Permission Denied" : "This page didn't load"}
        </h1>

        <p className="text-sm text-muted-foreground">
          {isAuthError
            ? "Your session may have expired or you do not have authorization to view this resource."
            : "Something went wrong while displaying this page."}
        </p>

        {errorMessage && (
          <div className="text-left bg-muted p-3 rounded-md text-xs font-mono text-muted-foreground overflow-x-auto max-h-32 border border-border">
            {errorMessage}
          </div>
        )}

        <div className="mt-6 flex flex-wrap justify-center gap-2 pt-2 border-t border-border">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="inline-flex items-center justify-center rounded-md bg-primary px-4 py-2 text-sm font-medium text-primary-foreground transition-colors hover:bg-primary/90"
          >
            Try again
          </button>
          <a
            href="/login"
            className="inline-flex items-center justify-center rounded-md border border-input bg-background px-4 py-2 text-sm font-medium text-foreground transition-colors hover:bg-accent"
          >
            Sign In
          </a>
          <a
            href="/"
            className="inline-flex items-center justify-center rounded-md border border-input bg-background px-4 py-2 text-sm font-medium text-foreground transition-colors hover:bg-accent"
          >
            Go home
          </a>
        </div>
      </div>
    </div>
  );
}

